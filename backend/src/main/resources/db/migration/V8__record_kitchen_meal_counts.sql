CREATE TABLE kitchen_meal_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    meal_date DATE NOT NULL,
    normal_count BIGINT NOT NULL CHECK (normal_count >= 0),
    special_count BIGINT NOT NULL CHECK (special_count >= 0),
    reported_by BIGINT NOT NULL REFERENCES users(id),
    reported_at TIMESTAMP NOT NULL
);

CREATE INDEX idx_kitchen_meal_reports_date_id ON kitchen_meal_reports (meal_date, id DESC);
